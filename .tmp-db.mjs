import { config } from "dotenv";
config({ path: ".env.local" });
import pg from "pg";
const client = new pg.Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 15000 });
await client.connect();
const t = Date.now();
const meta = await client.query("select id, octet_length(history_image) as bytes, history_image_mime, updated_at from shop_settings");
console.log("meta ms:", Date.now() - t, meta.rows);
const t2 = Date.now();
const full = await client.query("select history_image from shop_settings where id = $1", ["main"]);
const val = full.rows[0]?.history_image;
console.log("full ms:", Date.now() - t2, "bytes:", val?.length, "ctor:", val?.constructor?.name);
await client.end();
